import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import ts from "typescript";

const source = readFileSync("src/lib/workoutEditorSteps.ts", "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
vm.runInNewContext(compiled, { exports });
const imported = { type: "interval", duration_type: "distance", duration_value: 1, target_pace: { slower_sec_per_km: 310, faster_sec_per_km: 290 }, target_power: { low: 180, high: 220 }, target_hr: { low: 140, high: 160 }, target_cadence: { low: 85, high: 95 }, exercise: "PULL_UP", stroke: "free", equipment: "pull_buoy", extra: "preserved" };
const result = exports.stripEditableSteps([{ ...imported, _id: "a" }, { _id: "b", reps: 3, metadata: "kept", steps: [{ ...imported, _id: "c" }] }]);
assert.equal(JSON.stringify(result), JSON.stringify([imported, { reps: 3, metadata: "kept", steps: [imported] }]));
assert.equal(exports.parseTargetRange("", ""), null);
assert.equal(exports.parseTargetRange("120", ""), undefined);
assert.equal(exports.parseTargetRange("120", "120"), undefined);
assert.equal(exports.parseTargetRange("160", "120"), undefined);
assert.equal(JSON.stringify(exports.parseTargetRange("120.5", "160")), JSON.stringify({ low: 120.5, high: 160 }));
assert.equal(exports.validPoolLength(""), true);
assert.equal(exports.validPoolLength("9"), false);
assert.equal(exports.validPoolLength("25"), true);
assert.equal(exports.validPoolLength("101"), false);
const editor = readFileSync("src/components/WorkoutEditor.tsx", "utf8");
const draft = readFileSync("src/app/(tabs)/week/programs/drafts/[id]/page.tsx", "utf8");
assert.match(editor, /Esercizio importato/);
assert.match(editor, /!EXERCISE_OPTIONS\.some\(\(\[value\]\) => value === step\.exercise\)/);
assert.match(editor, /sport === "swimming" && <div[^>]*><Field label="Lunghezza vasca/);
assert.match(editor, /Cadenza \(passi\/min\)/);
assert.match(editor, /usePlanQuery\(mode !== "draft"\)/);
assert.match(editor, /if \(props\.mode === "draft"\) \{[\s\S]*?await props\.onSave\(session\)[\s\S]*?return;[\s\S]*?if \(mode !== "garmin"\)/);
assert.match(draft, /expected_revision:draft\.revision/);
assert.match(draft, /mode="draft"[\s\S]*?onSave=\{async updated=>\(await patch\(\{sessions:/);
console.log("Draft editor metadata round-trip and draft save routing passed.");
